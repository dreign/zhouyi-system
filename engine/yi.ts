// 大衍之数：49根蓍草
const YAN_NUM = 49;

// 三变取爻
export function change(grass: number, seed?: number): number {
  // 第一变
  let sky = seed ? ((seed % (grass - 1)) + 1) : Math.floor(Math.random() * (grass - 1)) + 1;
  let land = grass - sky - 1;
  let human = 1;
  
  // 去除余数
  sky = sky - (sky % 4 || 4);
  land = land - (land % 4 || 4);
  human = human - (human % 4 || 4);
  
  grass = sky + land + human;
  
  // 第二变
  sky = seed ? (((seed * 7) % (grass - 1)) + 1) : Math.floor(Math.random() * (grass - 1)) + 1;
  land = grass - sky - 1;
  human = 1;
  
  sky = sky - (sky % 4 || 4);
  land = land - (land % 4 || 4);
  human = human - (human % 4 || 4);
  
  grass = sky + land + human;
  
  // 第三变
  sky = seed ? (((seed * 13) % (grass - 1)) + 1) : Math.floor(Math.random() * (grass - 1)) + 1;
  land = grass - sky - 1;
  human = 1;
  
  sky = sky - (sky % 4 || 4);
  land = land - (land % 4 || 4);
  human = human - (human % 4 || 4);
  
  grass = sky + land + human;
  
  // 计算爻值：6(老阴)、7(少阳)、8(少阴)、9(老阳)
  return Math.floor(grass / 4);
}

// 起卦（6爻）
export function generateGua(seeds?: number[]): string {
  let guaCode = '';
  for (let i = 0; i < 6; i++) {
    const yao = change(YAN_NUM, seeds?.[i]);
    // 阳爻(1)：7、9；阴爻(0)：6、8
    guaCode += (yao === 7 || yao === 9) ? '1' : '0';
  }
  return guaCode;
}

// 金钱卦起卦
export function coinsDivination(coins?: number[]): string {
  let guaCode = '';
  for (let i = 0; i < 6; i++) {
    // 3枚铜钱：正面记3，背面记2，总和为6(老阴)、7(少阳)、8(少阴)、9(老阳)
    const coin = coins?.[i] ?? Math.floor(Math.random() * 4) + 6;
    guaCode += (coin === 7 || coin === 9) ? '1' : '0';
  }
  return guaCode;
}

// 数字卦起卦
export function numberDivination(numbers: number[]): string {
  let guaCode = '';
  for (let i = 0; i < 6; i++) {
    const num = numbers[i] ?? Math.floor(Math.random() * 10) + 1;
    // 奇数为阳，偶数为阴
    guaCode += (num % 2 === 1) ? '1' : '0';
  }
  return guaCode;
}

