// 获取卦信息
export function getGuaInfo(guaCode: string): {
  code: string;
  name: string;
  fullName: string;
  summary: string;
  symbol: string;
  guaci?: string;
  yaoci?: string[];
  interpretation?: string;
  vernacular?: string;
  yaociVernacular?: string[];
} {
  const basic = guaCi[guaCode];
  const details = guaDetails[guaCode];
  
  return {
    code: guaCode,
    name: basic ? basic[0] : '未知卦',
    fullName: basic ? basic[1] : '',
    summary: basic ? basic[2] : '',
    symbol: guaCodeToSymbol[guaCode] || '?',
    guaci: details?.guaci,
    yaoci: details?.yaoci,
    interpretation: details?.interpretation || basic?.[2],
    vernacular: details?.vernacular,
    yaociVernacular: details?.yaociVernacular
  };
}

// 计算变卦
export function getBianGua(guaCode: string, seeds?: number[]): string {
  if (!seeds || seeds.length === 0) {
    return guaCode;
  }
  
  let bianCode = '';
  for (let i = 0; i < 6; i++) {
    const yaoValue = seeds[i] || change(YAN_NUM, seeds[i]);
    // 6(老阴)变阳，9(老阳)变阴，7(少阳)和8(少阴)不变
    const originalBit = guaCode[i];
    if (yaoValue === 6) {
      bianCode += '1'; // 老阴变阳
    } else if (yaoValue === 9) {
      bianCode += '0'; // 老阳变阴
    } else {
      bianCode += originalBit; // 不变
    }
  }
  return bianCode;
}

// 获取动爻位置
export function getDongYao(seeds: number[]): number[] {
  const dongYao: number[] = [];
  for (let i = 0; i < seeds.length; i++) {
    const yaoValue = seeds[i] || change(YAN_NUM, seeds[i]);
    // 6(老阴)和9(老阳)是动爻
    if (yaoValue === 6 || yaoValue === 9) {
      dongYao.push(6 - i); // 从下往上数
    }
  }
  return dongYao;
}

// 生成占卜结果
export interface DivinationResult {
  benGua: ReturnType<typeof getGuaInfo>;
  bianGua?: ReturnType<typeof getGuaInfo>;
  dongYao: number[];
  yaos: Array<{ position: number; type: 'yang' | 'yin'; text?: string; vernacularText?: string; isDong: boolean }>;
}

export function divine(method: 'coins' | 'number' | 'random', numbers?: number[]): DivinationResult {
  let seeds: number[];
  let guaCode: string;
  
  switch (method) {
    case 'coins':
      seeds = numbers?.slice(0, 6) || Array.from({ length: 6 }, () => Math.floor(Math.random() * 4) + 6);
      guaCode = coinsDivination(seeds);
      break;
    case 'number':
      seeds = numbers?.slice(0, 6) || Array.from({ length: 6 }, () => Math.floor(Math.random() * 10) + 1);
      guaCode = numberDivination(seeds);
      break;
    default:
      seeds = Array.from({ length: 6 }, () => Math.floor(Math.random() * 100));
      guaCode = generateGua(seeds);
  }
  
  const bianGuaCode = getBianGua(guaCode, seeds);
  const dongYao = getDongYao(seeds);
  
  const benGuaInfo = getGuaInfo(guaCode);
  const bianGuaInfo = bianGuaCode !== guaCode ? getGuaInfo(bianGuaCode) : undefined;
  
  // 构建爻信息（包含白话翻译）
  const yaos = guaCode.split('').map((bit, index) => {
    const position = 6 - index;
    const yaoValue = seeds[index];
    const isDong = yaoValue === 6 || yaoValue === 9;
    const yaoci = benGuaInfo.yaoci?.[5 - index];
    const yaociVernacular = benGuaInfo.yaociVernacular?.[5 - index];
    
    return {
      position,
      type: bit === '1' ? 'yang' as const : 'yin' as const,
      text: yaoci,
      vernacularText: yaociVernacular,
      isDong
    };
  });
  
  return {
    benGua: benGuaInfo,
    bianGua: bianGuaInfo,
    dongYao,
    yaos
  };
}