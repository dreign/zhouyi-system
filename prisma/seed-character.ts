async function seedCharacterData() {
  console.log('开始导入常用汉字数据...\n');

  let successCount = 0;
  let failCount = 0;

  for (const charData of commonCharacters) {
    try {
      await prisma.characterData.upsert({
        where: { char: charData.char },
        update: charData,
        create: charData,
      });
      successCount++;
    } catch (error) {
      console.error(`✗ 导入失败: ${charData.char} -`, error);
      failCount++;
    }
  }

  console.log(`\n✓ 成功导入 ${successCount} 个汉字`);
  if (failCount > 0) {
    console.log(`✗ 导入失败 ${failCount} 个汉字`);
  }
  console.log('\n汉字数据导入完成！');
}

async function main() {
  try {
    await seedCharacterData();
  } catch (error) {
    console.error('导入过程中发生错误:', error);
    throw error;
  } finally {
    await prisma.$disconnect();
  }
}

main();
